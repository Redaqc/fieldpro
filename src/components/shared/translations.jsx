export function useTranslation(lang = 'fr') {
  return (key) => {
    const keys = key.split('.');
    let value = translations[lang] || translations.fr;
    
    for (const k of keys) {
      value = value?.[k];
      if (value === undefined) break;
    }
    
    return value || translations.fr[key] || key;
  };
}